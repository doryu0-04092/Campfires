-- 【役割】パスワードの変更（F-24）と、パスワードの再設定（F-25）のためのマイグレーション。
-- 【なぜ必要か】
--   ① パスワードを変えたら、ほかの端末に残っているログイン（セッション）を止めたい。
--      そのために「最後にパスワードを変えた日時」を users に記録し、それより前に作られたセッションを使えなくする
--      （ActiveUserFilter が、API の呼び出しのたびに比べる）。
--   ② パスワードを忘れた人が、メールで届くリンク（使い捨ての合言葉＝トークン付き）から、パスワードを決め直せるようにする。
--      トークンそのものは保存せず、SHA-256 で変換した値だけを保存する（データベースの中身が漏れても、リンクを作り直せないように）。

-- ============================================================
-- ユーザー：最後にパスワードを変えた日時
-- ============================================================
-- 一度も変えていなければ NULL。アプリ（Java）の時計の日時を、ミリ秒の単位にそろえて入れる
-- （セッションを作った日時も、アプリの時計のミリ秒なので、同じ時計・同じ細かさで比べられるようにするため）
ALTER TABLE users ADD COLUMN password_changed_at TIMESTAMPTZ;

-- ============================================================
-- パスワードの再設定のトークン（要件定義書 5.13）
-- ============================================================
CREATE TABLE password_reset_tokens (
    id          BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- だれのパスワードを再設定するためのトークンか
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    -- トークンを SHA-256 で変換した値（16進数の64文字）。トークンそのものは保存しない。
    -- UNIQUE：同じ値は2つ入らない（探すときの索引にもなる）
    token_hash  CHAR(64)     NOT NULL UNIQUE,
    -- 有効期限（作ってから30分）
    expires_at  TIMESTAMPTZ  NOT NULL,
    -- 使った日時、または無効にした日時（新しいトークンを作った・パスワードを変えたとき）。まだ使えるなら NULL
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ユーザーごとのトークンを探す（古いトークンを無効にする、アカウントの削除で消す）ための索引
CREATE INDEX password_reset_tokens_user ON password_reset_tokens (user_id);
